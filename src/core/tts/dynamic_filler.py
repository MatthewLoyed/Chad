"""
Dynamic contextual filler generation — live voice mode epic #291 Phase 3.

Replaces VoiceModeController's canned filler-phrase rotation with a short,
query-tailored acknowledgment generated by the same fast local model used for
the voice lane (``local_models.category_models.voice``, resident from the
lane itself — no load-wait needed). A single raw HTTP call to LM Studio,
mirroring the request shape in ``src/infrastructure/tools/selection/llm_selector.py``
but far simpler: no model-load/unload handling, fail fast on any error so the
caller falls back to the canned rotation.

This is deliberately callable straight from the Limb: LM Studio is a local HTTP
service on the same machine, not a Brain internal, so reaching it directly here
doesn't cross the Brain/Limb boundary (unlike calling into ConversationOrchestrator
or TurnCoordinator, which would).
"""

import asyncio
import json
import urllib.error
import urllib.request
from typing import Optional

from src.shared.logger import setup_logger

logger = setup_logger("DynamicFiller")

_SYSTEM_PROMPT = (
    "You generate a single short spoken filler phrase (3-6 words) acknowledging "
    "a user's request while the real answer is still being prepared. Examples: "
    '"Let me check on that", "One moment, looking into it", "Give me a second '
    'with that one". Reply with ONLY the phrase — no quotes, no punctuation-heavy '
    "formatting, no explanation."
)

# Issue #654 follow-up: 0.5s assumed near-instant local model calls — direct
# benchmarking (evals/voice_quick_model_bench.py) disproved that: the floor for
# ANY local model call on this hardware is several seconds, regardless of prompt
# size. 0.5s guaranteed this call always timed out and always fell back to canned.
# Bumped to a real budget; VoiceModeController's `dynamic_filler_wait` is what
# actually bounds the caller's total added wait (this is just the HTTP-level cap
# so a truly hung request doesn't block that follow-up window forever).
_DEFAULT_TIMEOUT_S = 4.0
_DEFAULT_MAX_TOKENS = 24


async def generate_dynamic_filler(
    text: str,
    model: str,
    base_url: str = "http://localhost:1234/v1",
    timeout: float = _DEFAULT_TIMEOUT_S,
) -> Optional[str]:
    """Ask the resident fast local model for a one-line filler tailored to ``text``.

    Returns None on any failure (unreachable, timeout, malformed response, empty
    string) so the caller can fall back to the canned rotation without special-casing.
    """
    try:
        return await asyncio.to_thread(_generate_sync, text, model, base_url, timeout)
    except Exception as e:
        logger.debug(f"Dynamic filler call failed: {e}")
        return None


def _generate_sync(text: str, model: str, base_url: str, timeout: float) -> Optional[str]:
    payload = {
        "model": model,
        "messages": [
            {"role": "system", "content": _SYSTEM_PROMPT},
            {"role": "user", "content": text},
        ],
        "temperature": 0.7,
        "max_tokens": _DEFAULT_MAX_TOKENS,
    }
    # Qwen3.x traps output inside thinking blocks unless thinking is disabled —
    # a filler phrase has no room for a reasoning budget.
    if "qwen3" in model.lower():
        payload["extra_body"] = {"chat_template_kwargs": {"enable_thinking": False}}

    req = urllib.request.Request(
        base_url.rstrip("/") + "/chat/completions",
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            body = json.loads(resp.read())
    except (urllib.error.URLError, TimeoutError, OSError) as e:
        logger.debug(f"Dynamic filler unreachable: {e}")
        return None

    try:
        phrase = body["choices"][0]["message"]["content"].strip().strip('"')
    except (KeyError, IndexError, AttributeError):
        return None
    return phrase or None
