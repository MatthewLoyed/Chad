import os
import re
import base64
from typing import Dict, Any, Optional

from src.tools.base_tool import BaseTool
from src.tools.coding.code_verify import verify_source_or_html
from src.shared.logger import setup_logger
from src.shared.config_manager import ConfigManager
from src.shared.file_registry import file_registry

logger = setup_logger("HTMLBuilder")

class HTMLBuilderTool(BaseTool):
    """
    A tool that packages HTML content into a downloadable artifact. 
    Chad writes the HTML, and this tool handles the 'Save and Download' flow.
    """
    
    name: str = "build_html_file"
    description: str = (
        "Package HTML content as a downloadable file. Chad should write the complete HTML himself first, "
        "then call this tool to save it. Parameters: html_content (the full HTML string Chad wrote), "
        "filename (slug like my-app.html)."
    )
    category: str = "filesystem"
    is_side_effecting: bool = True

    def get_schema(self) -> Dict[str, Any]:
        """Return the function schema for this tool."""
        return {
            "name": self.name,
            "description": self.description,
            "parameters": {
                "type": "object",
                "properties": {
                    "html_content": {
                        "type": "string",
                        "description": "The complete, functional HTML code generated by Chad."
                    },
                    "filename": {
                        "type": "string",
                        "description": "A short descriptive filename (e.g., 'farm-sim.html')."
                    }
                },
                "required": ["html_content", "filename"]
            }
        }

    async def execute(self, html_content: str, filename: str, **kwargs) -> Dict[str, Any]:
        """
        Takes raw HTML from Chad, cleans it, and registers it for download.
        """
        try:
            # 1. Strip markdown fences defensively
            clean_html = self._strip_markdown_fences(html_content)

            if not filename.endswith(".html"):
                filename += ".html"

            if ConfigManager.get("tools.code_verify_enabled", True):
                ok, verify_err = verify_source_or_html(filename, clean_html)
                if not ok:
                    return {
                        "success": False,
                        "error": verify_err,
                    }

            if not clean_html or len(clean_html) < 20:
                return {
                    "success": False,
                    "error": "HTML content is too short or empty."
                }

            # 2. Store in FileRegistry
            data_base64 = base64.b64encode(clean_html.encode('utf-8')).decode('utf-8')
            token = file_registry.store_file(filename, data_base64, "text/html")

            logger.info(f"HTML packaged and registered: {filename} (Token: {token})")

            return {
                "success": True,
                "result": f"HTML artifact '{filename}' has been successfully packaged.",
                "filename": filename,
                "download_token": token,
                "auto_preview": True,
            }

        except Exception as e:
            logger.error(f"HTML packaging failed: {e}", exc_info=True)
            return {
                "success": False,
                "error": f"Failed to package HTML: {str(e)}"
            }

    @staticmethod
    def _strip_markdown_fences(text: str) -> str:
        """Removes ```html and ``` blocks, or unwraps JSON tool payloads if present."""
        if not text:
            return ""
        # Remove opening fence
        text = re.sub(r'^```(?:html|json)?\s*', '', text, flags=re.IGNORECASE | re.MULTILINE)
        text = re.sub(r'^```\s*', '', text, flags=re.MULTILINE)
        # Remove closing fence
        text = re.sub(r'\s*```$', '', text, flags=re.MULTILINE).strip()

        # If wrapped in raw JSON tool call payload
        trimmed = text
        if trimmed.startswith("json\n") or trimmed.startswith("json\r\n"):
            trimmed = trimmed.split("\n", 1)[1].strip()
        if trimmed.startswith("{") and ("html_content" in trimmed or "content" in trimmed):
            try:
                import json
                data = json.loads(trimmed)
                if isinstance(data, dict):
                    args = data.get("arguments") or data
                    if isinstance(args, dict):
                        candidate = args.get("html_content") or args.get("content")
                        if candidate and isinstance(candidate, str) and ("<html" in candidate.lower() or "<!doctype" in candidate.lower()):
                            return candidate.strip()
            except Exception:
                pass

        return text.strip()

    def validate_params(self, html_content: str = None, filename: str = None, **kwargs) -> tuple[bool, Optional[str]]:
        if not html_content or len(html_content.strip()) < 10:
            return False, "html_content is required and must be valid HTML"
        if not filename or len(filename.strip()) < 3:
            return False, "filename is required"
        return True, None


HtmlBuilderTool = HTMLBuilderTool


_READABLE_MIME_PREFIXES = ("text/", "application/json")


class ReadArtifactTool(BaseTool):
    """
    Reads back the current text content of a previously built artifact (by filename or
    download_token), so an edit request ("make it more pink") can be applied to the real
    file instead of the model guessing/re-inventing content from scratch. No sandbox or
    execution environment is needed for this — same as Claude Artifacts, a text artifact
    is just a file to re-read and rewrite in place.
    """

    name: str = "read_artifact"
    description: str = (
        "Read back the current content of a previously built HTML/CSS/JS/text artifact, by "
        "filename or download_token, before editing it. Use this whenever the user asks to "
        "change/edit/tweak an existing artifact rather than build a new one."
    )
    category: str = "filesystem"

    def format_action(self, params: Dict[str, Any]) -> str:
        target = params.get("filename") or params.get("token") or "artifact"
        return f"Reading artifact: {target}"

    def get_schema(self) -> Dict[str, Any]:
        return {
            "name": self.name,
            "description": self.description,
            "parameters": {
                "type": "object",
                "properties": {
                    "filename": {
                        "type": "string",
                        "description": "The artifact's filename (e.g. 'anime-gallery.html'). Provide this or token.",
                    },
                    "token": {
                        "type": "string",
                        "description": "The artifact's download_token, if known. Provide this or filename.",
                    },
                },
                "required": [],
            },
        }

    async def execute(self, filename: Optional[str] = None, token: Optional[str] = None, **kwargs) -> Dict[str, Any]:
        try:
            match = None
            if token:
                match = file_registry.get_file(token)
            if not match and filename:
                target = filename.strip().lower()
                for art in file_registry.list_artifacts():
                    if art["name"].lower() == target:
                        match = file_registry.get_file(art["token"])
                        break

            if not match:
                return {
                    "success": False,
                    "error": f"No artifact found for {'token ' + token if token else 'filename ' + str(filename)}. "
                             "Check the exact filename from the conversation, or ask the user for it.",
                }

            mime = match.get("mime", "")
            if not any(mime.startswith(p) for p in _READABLE_MIME_PREFIXES):
                return {
                    "success": False,
                    "error": f"Artifact '{match.get('name')}' is binary ({mime}); it can't be read back as text.",
                }

            content = base64.b64decode(match["data"]).decode("utf-8")
            return {
                "success": True,
                "filename": match.get("name"),
                "token": match.get("token"),
                "content": content,
                "result": f"Read {len(content)} chars from '{match.get('name')}'. Edit this content and call "
                          "build_html_file/write_file with the SAME filename to overwrite it.",
            }
        except Exception as e:
            logger.error(f"Failed to read artifact: {e}", exc_info=True)
            return {"success": False, "error": f"Failed to read artifact: {str(e)}"}
