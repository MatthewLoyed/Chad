def get_all_connector_schemas() -> List[Dict[str, Any]]:
    """Return list of all connector schemas."""
    return list(CONNECTOR_SCHEMAS.values())


def get_connector_schema(connector_id: str) -> Optional[Dict[str, Any]]:
    """Retrieve schema for a specific connector by ID."""
    if not connector_id:
        return None
    key = str(connector_id).strip().lower()
    return CONNECTOR_SCHEMAS.get(key)
